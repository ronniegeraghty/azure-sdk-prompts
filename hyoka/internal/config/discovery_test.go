func TestDiscoverProjectDir_Found(t *testing.T) {
	// Create a temp tree: root/.git + root/.hyoka/configs
	root := t.TempDir()
	os.MkdirAll(filepath.Join(root, ".git"), 0755)
	os.MkdirAll(filepath.Join(root, ".hyoka", "configs"), 0755)

	proj := DiscoverProjectDir(root)
	if !proj.Found() {
		t.Fatal("expected to find .hyoka directory")
	}
	if proj.Root != filepath.Join(root, ".hyoka") {
		t.Errorf("expected root %q, got %q", filepath.Join(root, ".hyoka"), proj.Root)
	}
}

func TestDiscoverProjectDir_FoundInParent(t *testing.T) {
	root := t.TempDir()
	os.MkdirAll(filepath.Join(root, ".git"), 0755)
	os.MkdirAll(filepath.Join(root, ".hyoka"), 0755)
	child := filepath.Join(root, "sub", "deep")
	os.MkdirAll(child, 0755)

	proj := DiscoverProjectDir(child)
	if !proj.Found() {
		t.Fatal("expected to discover .hyoka from child directory")
	}
	if proj.Root != filepath.Join(root, ".hyoka") {
		t.Errorf("expected root %q, got %q", filepath.Join(root, ".hyoka"), proj.Root)
	}
}

func TestDiscoverProjectDir_StopsAtGitRoot(t *testing.T) {
	// root/.hyoka exists but child/.git is present — discovery from child
	// should stop at child (the git root) and not find root/.hyoka.
	root := t.TempDir()
	os.MkdirAll(filepath.Join(root, ".hyoka"), 0755)

	child := filepath.Join(root, "child")
	os.MkdirAll(filepath.Join(child, ".git"), 0755)

	proj := DiscoverProjectDir(child)
	if proj.Found() {
		t.Errorf("should NOT discover .hyoka above git root, but found %q", proj.Root)
	}
}

